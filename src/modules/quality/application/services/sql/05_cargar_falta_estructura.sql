    INSERT INTO articulo_estructuras (
        "codigoPadre", "codigoComponente", cantidad, activo, "createdAt", "updatedAt"
    )
    SELECT
        lb.padre,
        lb.comp,
        lb.cant,
        true,
        now(),
        now()
    FROM lineas_bom lb
    WHERE NOT EXISTS (
        SELECT 1 FROM articulo_estructuras ae
        WHERE ae."codigoPadre" = lb.padre AND ae."codigoComponente" = lb.comp AND ae.activo = true
    )
    RETURNING 1
),
default_machine AS (
    SELECT id AS machine_type_id
    FROM machine_types
    WHERE category = 'TEJEDURIA'
    ORDER BY CASE WHEN name ILIKE '%144%' OR name ILIKE '%156%' OR name ILIKE '%LONATI%' THEN 0 ELSE 1 END, name
    LIMIT 1
),
ins_maq AS (
    INSERT INTO articulo_machine_types (
        "articuloId", "machineTypeId", "cycleTimeSeconds", "timeSource", status, preferida, "createdAt"
    )
    SELECT
        ia.id,
        dm.machine_type_id,
        95,
        'ESTIMADO_FAMILIA',
        'ESTIMADO',
        true,
        now()
    FROM ins_art ia
    CROSS JOIN default_machine dm
    WHERE ia.etapa = 'TEJIDO'
    ON CONFLICT ("articuloId", "machineTypeId") DO NOTHING
    RETURNING 1
)
